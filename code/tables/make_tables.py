"""Write the paper's tables (LaTeX tabular bodies) to paper/tables/.

  tab1_composite.tex   Table 1: N versus bystander size (computed here)
  tab2_q2grid.tex      Table 2: sign of q2 (code/checks/asymmetry_checks.py)
  tab3_neer.tex        Table 3: bystander reversal and NEER thresholds
  tabC1_tau0.tex       Appendix C.1: common external tariff
  tabC3_sens.tex       Appendix C.3: sensitivities of the threshold
Appendix C numbers are read from code/results/appendix_c.json, written by
code/checks/appendix_c.py (run that first; run_all.py does)."""
import json
import os
import sys

import numpy as np
from scipy.optimize import brentq

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "code"))
sys.path.insert(0, os.path.join(ROOT, "code", "checks"))

import asymmetry_checks as ac  # noqa: E402
from model import closed_forms as cf  # noqa: E402
from model import linear as lin  # noqa: E402

OUT = os.path.join(ROOT, "paper", "tables")
os.makedirs(OUT, exist_ok=True)


def write(name, text):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        fh.write("% generated by code/tables/make_tables.py -- do not edit\n" + text)
    print("wrote paper/tables/" + name)


# ------------------------------------------------------------ Table 1
CAL = cf.US_LIKE
cc = np.zeros((3, 3)); cc[0, 1] = 1.0


def comp_threshold(N, ordinary):
    f = lambda r: lin.response(cf.composite_base(N, CAL["aD"], CAL["aT"], CAL["eta"], r,
                                                 ordinary_eta=ordinary), cc)[1]
    return brentq(f, 1.0001, 40.0, xtol=1e-12)


rows = []
for N in (3, 4, 5, 8):
    true = N * cf.rhoD(**CAL)
    comp = comp_threshold(N, False)
    assert abs(comp - true) < 1e-9
    rows.append(r"%d & %.2f & %.2f & %.2f & %.2f \\" % (
        N, true, comp, comp_threshold(N, True), cf.eta_C(N, CAL["aD"], CAL["eta"], 4.0)))
write("tab1_composite.tex", "\n".join(rows) + "\n")

# ------------------------------------------------------------ Table 2
grid = ac.q2_grid()
lines = []
for row in grid:
    cells = []
    for c in row:
        if c["sign_q2"] == 0:
            cells.append(r"$\mathbf{0}$")   # symmetric benchmark cell, set in bold
        elif c["sign_q2"] > 0:
            cells.append(r"$+$\,{\footnotesize %.1f}" % c["roots"][-1] if c["roots"][-1] < 100
                         else r"$+$\,{\footnotesize $>$100}")
        else:
            cells.append(r"$-$")
        assert c["mml"] and not c["two_root"] and c["qhat"][2] < 0
    lines.append(r"%g & " % row[0]["S_B"] + " & ".join(cells) + r" \\")
write("tab2_q2grid.tex", "\n".join(lines) + "\n")

# ------------------------------------------------------------ Table 3
lines = []
for t in (0.75, 0.85, 0.90):
    r = ac.table3_row(t)
    assert r["mml_on_grid"]
    lines.append(r"%.2f & %.2f & %.2f & %.2f & %.2f \\" % (
        r["w_AC"], r["L_B"], r["rho_dnuC"], r["rho_neer"], r["rho_tot_primfixed"]))
write("tab3_neer.tex", "\n".join(lines) + "\n")

# ------------------------------------------------------------ Appendix C
res = json.load(open(os.path.join(ROOT, "code", "results", "appendix_c.json")))
f2 = res["fig2"]
lines = [r"$N=%s$ & %.2f & %.2f & %.2f \\" % (N, f2["C1_ratio"][N]["0.25"], f2["C1_ratio"][N]["0.5"],
                                               f2["C1_ratio"][N]["1.0"]) for N in ("3", "5")]
write("tabC1_tau0.tex", "\n".join(lines) + "\n")

us = res["us_like"]
lab = {"beta_AB": r"$\beta_{AB}$", "L_B": r"$L_B$", "L_C": r"$L_C$", "aD_A": r"$\alpha_D^A$"}
lines = [r"%s & $%+.2f$ & $%+.2f$ \\" % (lab[k], f2["C3_sensitivities"][k], us["C3_sensitivities"][k])
         for k in ("beta_AB", "L_B", "L_C", "aD_A")]
write("tabC3_sens.tex", "\n".join(lines) + "\n")
